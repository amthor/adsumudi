local config = require("rechenblatt.config")

describe("config.parse", function()
	it("Voreinstellung: Plus/Minus, 1-100, 5 Minuten", function()
		local o = config.parse({})
		assert.are.same({ "add", "sub" }, o.operations)
		assert.are.equal(1, o.min)
		assert.are.equal(100, o.max)
		assert.are.equal(5, o.minutes)
		-- assert.are.equal(22, o.count)
	end)

	it("--debug schaltet den Debug-Modus ein", function()
		assert.is_false(config.parse({}).debug)
		assert.is_true(config.parse({ "--debug" }).debug)
		assert.is_true(config.parse({ "-d" }).debug)
	end)

	it("--anzahl hat Vorrang vor --minuten", function()
		local o = config.parse({ "-t", "10", "-n", "8" })
		assert.are.equal(8, o.count)
		assert.is_nil(o.minutes)
	end)

	it("versteht Rechenzeichen und Namen", function()
		local o = config.parse({ "-r", "+,*,:,minus" })
		assert.are.same({ "add", "mul", "div", "sub" }, o.operations)
	end)

	it("meldet ungültige Eingaben", function()
		assert.has_error(function()
			config.parse({ "-r", "wurzel" })
		end)
		assert.has_error(function()
			config.parse({ "--max", "abc" })
		end)
		assert.has_error(function()
			config.parse({ "--min", "50", "--max", "10" })
		end)
		assert.has_error(function()
			config.parse({ "--foo" })
		end)
		assert.has_error(function()
			config.parse({ "-n" })
		end)
	end)

	it("--blattcode legt Rechenarten, Zahlenbereich, Anzahl und Seed fest", function()
		local o = config.parse({ "--blattcode", "1-MD-2-50-12-48213", "-l", "--titel", "Nachdruck" })
		assert.are.same({ "mul", "div" }, o.operations)
		assert.are.equal(2, o.min)
		assert.are.equal(50, o.max)
		assert.are.equal(12, o.count)
		assert.are.equal(48213, o.seed)
		assert.is_nil(o.minutes)
		assert.is_true(o.solutions)
		assert.are.equal("Nachdruck", o.title)
		assert.are.equal(48213, config.parse({ "-c", "1-AS-1-100-22-48213" }).seed)
	end)

	it("--blattcode lässt sich nicht mit festlegenden Optionen kombinieren", function()
		for _, extra in ipairs({ { "-r", "add" }, { "--min", "2" }, { "--max", "50" }, { "-n", "4" }, { "-t", "3" }, { "-s", "1" } }) do
			local args = { "--blattcode", "1-AS-1-100-22-1", extra[1], extra[2] }
			assert.has_error(function()
				config.parse(args)
			end)
		end
	end)

	it("prüft den Seed-Bereich und liefert ganze Zahlen", function()
		assert.has_error(function()
			config.parse({ "-s", "-1" })
		end)
		assert.has_error(function()
			config.parse({ "-s", "4294967296" })
		end)
		assert.are.equal("integer", math.type(config.parse({ "-s", "5.0" }).seed))
	end)
end)
